#!/usr/bin/env python3
"""Replace the lab's seat/preset names in results/results.csv with role words.

The exported CSV is generated by scripts/export_results.py from a private source CSV whose `notes` column
names the lab's own presets ("seats"). Those names are internal shorthand, so this script rewrites them to
role words before publication:

    checker preset, writer preset, audit preset, audit preset (no-think arm), aux preset,
    summary preset, 26B remote seat, local router, document-audit protocol

Model names (gemma4:e4b, bolt-e4b, FrogNano-4B-2609-IQ4_XS, ...) are public and are NEVER touched: they are
the substance of the results. Numbers, scores, row order and the column set are preserved; only text columns
(`notes`, `score`, `model`, ...) are rewritten, and `notes` is the only one that normally changes.

Idempotent: rules match seat names, not their replacements, so a second run is a no-op.

  python3 scripts/sanitize_results.py            rewrite the file in place, print what changed
  python3 scripts/sanitize_results.py --check    change nothing; exit 1 if the file still needs sanitising
  python3 scripts/sanitize_results.py --diff     print a unified diff instead of writing
"""
import argparse
import csv
import difflib
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "..", "results", "results.csv")

# Every seat token this script knows about. Used for the residual-leak guard, not for rewriting.
SEAT_TOKENS = [
    "frog-agent", "vision-text", "doc-audit", "bolt-agent", "bolt-ng-", "bolt-df-", "gemma26",
    "sum-granite", "sum-lfm", "sum-llama", "aux seat", "vtext-ng-", "frog-ng-",
]

CTX = r"(?:-(16k|24k|32k|40k|64k))?"

# text columns a rewrite may touch; every other column (scores, counts, dates, provenance) must stay byte-identical
TEXT_COLS = ("model", "test", "score", "metric_value", "metric_unit", "notes")

# (label, compiled pattern, replacement). Order matters: longer / more specific forms first.
RULES = [
    # --- seat names -------------------------------------------------------
    ("frog-agent", re.compile(r"(?<![\w-])frog-agent" + CTX + r"(?![\w-])"),
     lambda m: "checker preset" + (" (%s)" % m.group(1) if m.group(1) else "")),
    ("vision-text seat", re.compile(r"(?<![\w-])vision-text seat(?![\w-])"), "writer preset"),
    ("vision-text", re.compile(r"(?<![\w-])vision-text(?![\w-])"), "writer preset"),
    ("doc-audit", re.compile(r"(?<![\w-])doc-audit(?![\w-])"), "audit preset"),
    ("bolt-agent", re.compile(r"(?<![\w-])bolt-agent" + CTX + r"(?![\w-])"),
     lambda m: "audit preset (no-think arm)" + (" (%s)" % m.group(1) if m.group(1) else "")),
    ("bolt-ng-*", re.compile(r"(?<![\w-])bolt-ng-[a-z0-9-]+(?![\w-])"), "audit preset (no-think arm)"),
    ("gemma26", re.compile(r"(?<![\w-])gemma26(?![\w-])"), "26B remote seat"),
    # "router seat sum-<tag>" is one phrase; collapse it to the role word first
    ("router seat sum-*", re.compile(r"\brouter seat (?<![\w-])sum-[a-z0-9]+(?![\w-])"), "summary preset"),
    ("sum-*", re.compile(r"(?<![\w-])sum-[a-z0-9]+(?![\w-])"), "summary preset"),
    ("ex-aux seat", re.compile(r"(?<![\w-])[Ee]x-aux seat(?![\w-])"), "Former aux preset"),
    ("aux seat <tag>", re.compile(r"(?<![\w-])aux seat \S*?(16k|24k|32k|40k|64k)(?![\w-])"),
     "aux preset (\\1)"),
    ("aux seat", re.compile(r"(?<![\w-])aux seat(?![\w-])"), "aux preset"),
    # --- lab-local service and harness names the notes also carried --------
    ("router port", re.compile(r"\brouter :\d+\b"), "local router"),
    ("bakeoff protocol", re.compile(r"(?<![\w-])doc-seat-bakeoff-lc protocol(?![\w-])"),
     "document-audit protocol"),
    ("bakeoff grader", re.compile(r"(?<![\w-])doc-seat-bakeoff-grade(?![\w-])"),
     "the document-audit grader"),
]


def sanitize_text(text):
    """Return (new_text, [(label, count), ...])."""
    hits = []
    for label, pat, repl in RULES:
        text, n = pat.subn(repl, text)
        if n:
            hits.append((label, n))
    return text, hits


def load(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        rows = list(reader)
    return fields, rows


def render(fields, rows):
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=fields, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def sanitize_rows(fields, rows):
    totals = {}
    out = []
    for row in rows:
        new = dict(row)
        for col in TEXT_COLS:
            if col in new and new[col]:
                new[col], hits = sanitize_text(new[col])
                for label, n in hits:
                    totals[(col, label)] = totals.get((col, label), 0) + n
        out.append(new)
    return out, totals


def residual_leaks(rows):
    bad = []
    for i, row in enumerate(rows, 2):  # 2 = first data line in the file
        blob = (row.get("model", "") + " " + row.get("notes", "")).lower()
        for tok in SEAT_TOKENS:
            if tok in blob:
                bad.append((i, tok, row.get("test", ""), row.get("model", "")[:40]))
    return bad


def changed_columns(fields, old, new):
    return [f for f in fields if any(a[f] != b[f] for a, b in zip(old, new))]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", default=CSV_PATH, help="results CSV to sanitise (default: results/results.csv)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if anything would change")
    ap.add_argument("--diff", action="store_true", help="print a unified diff; do not write")
    a = ap.parse_args()

    fields, rows = load(a.csv)
    with open(a.csv, encoding="utf-8") as f:
        before = f.read()
    new_rows, totals = sanitize_rows(fields, rows)
    after = render(fields, new_rows)

    # invariants: same shape, same non-text values
    if len(new_rows) != len(rows):
        sys.exit("refusing: row count changed (%d -> %d)" % (len(rows), len(new_rows)))
    if [r["test"] for r in rows] != [r["test"] for r in new_rows]:
        sys.exit("refusing: test column changed")
    cols = changed_columns(fields, rows, new_rows)
    if any(c not in TEXT_COLS for c in cols):
        sys.exit("refusing: a non-text column changed: %s" % cols)

    leaks = residual_leaks(new_rows)
    if leaks:
        for i, tok, test, model in leaks:
            print("RESIDUAL %-12s line %d (%s, %s)" % (tok, i, test, model), file=sys.stderr)
        sys.exit("refusing: seat names still present after sanitising")

    if totals:
        print("rewrote %d value(s) in: %s" % (sum(totals.values()), ", ".join(sorted({c for c, _ in totals}))))
        for (col, label), n in sorted(totals.items()):
            print("  %-8s %-22s %d" % (col, label, n))
    else:
        print("nothing to do: no seat names left in %s" % os.path.relpath(a.csv))

    if a.diff:
        sys.stdout.writelines(difflib.unified_diff(
            before.splitlines(keepends=True), after.splitlines(keepends=True),
            fromfile="a/" + os.path.basename(a.csv), tofile="b/" + os.path.basename(a.csv)))
        return 0
    if a.check:
        return 1 if after != before else 0
    if after != before:
        with open(a.csv, "w", newline="", encoding="utf-8") as f:
            f.write(after)
    return 0


if __name__ == "__main__":
    sys.exit(main())
